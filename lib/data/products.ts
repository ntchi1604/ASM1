/* ------------------------------------------------------------------
   Truy vấn. Khi có backend, chỉ thay phần thân các hàm dưới đây.
   ------------------------------------------------------------------ */

export function getProductById(id: string): Product | undefined {
  return products.find((p) => p.id === id);
}

export function getProductBySlug(slug: string): Product | undefined {
  return products.find((p) => p.slug === slug);
}

export function getProductsByCategory(categorySlug: string): Product[] {
  return products.filter((p) => p.categorySlug === categorySlug);
}

/** Giá thấp nhất trong các đơn vị — dùng cho thẻ sản phẩm ở trang danh mục. */
export function getBaseUnit(product: Product) {
  return product.units.reduce((cheapest, unit) =>
    unit.price < cheapest.price ? unit : cheapest,
  );
}

/** Đơn vị mặc định hiển thị: đơn vị đầu tiên (thường là Hộp). */
export function getDefaultUnit(product: Product) {
  return product.units[0];
}

export function getProductsOnSale(): Product[] {
  return products.filter((p) => p.units.some((u) => u.originalPrice));
}

/** Không kê đơn, còn hàng — dùng cho khối gợi ý và bán chạy. */
export function getSellableProducts(): Product[] {
  return products.filter((p) => !p.prescriptionRequired && p.stock.total > 0);
}
